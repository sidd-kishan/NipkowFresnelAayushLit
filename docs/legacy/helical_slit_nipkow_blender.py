# ------------------------------------------------
# 14. RASTER ANIMATION
# ------------------------------------------------
#
# Every pixel gets:
#
#   frame before scan -> dark
#   scan frame         -> bright if smiley pixel = 1
#   immediately later  -> remains bright
#
# Therefore the smiley progressively builds itself.
#
# All keyframes are inserted now.
# Press PLAY afterwards.
# ------------------------------------------------

for index, (pix, px, py) in enumerate(pixel_objects):

    scan_frame = START_FRAME + index * FRAMES_PER_PIXEL

    # Before this pixel is scanned
    pix.hide_viewport = False
    pix.hide_render = False

    # Emission strength is controlled by material assignment.
    # We use object visibility to make the raster extremely obvious.
    #
    # OFF state
    pix.scale.z = 0.05
    pix.keyframe_insert(
        data_path="scale",
        index=2,
        frame=max(START_FRAME, scan_frame - 1)
    )

    # If it is a smiley pixel, turn it ON.
    if smiley_pixel(px, py, NX, NY):
        pix.scale.z = 1.0
        pix.keyframe_insert(
            data_path="scale",
            index=2,
            frame=scan_frame
        )

        # Give it the glowing material.
        # Material slots cannot be keyframed robustly across all Blender
        # versions, so the object starts as a bright material and its
        # scale controls when the visible pixel appears.
        if len(pix.data.materials) > 0:
            pix.data.materials[0] = MAT_PIXEL_ON

    else:
        # Keep blank pixel nearly invisible.
        pix.scale.z = 0.05
        pix.keyframe_insert(
            data_path="scale",
            index=2,
            frame=scan_frame
        )

    # Hold the scanned pixel.
    pix.keyframe_insert(
        data_path="scale",
        index=2,
        frame=END_FRAME
    )

