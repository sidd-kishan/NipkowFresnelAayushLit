# ------------------------------------------------
# 17. OPTICAL PATH INDICATOR
# ------------------------------------------------
#
# A thin line from drum toward the active screen area.
# This is a conceptual visualization, not a ray-tracing claim.
# ------------------------------------------------

def add_beam_segment(name, p1, p2, radius, material):
    p1 = Vector(p1)
    p2 = Vector(p2)

    mid = (p1 + p2) * 0.5
    direction = p2 - p1
    length = direction.length

    bpy.ops.mesh.primitive_cylinder_add(
        vertices=16,
        radius=radius,
        depth=length,
        location=mid
    )

    obj = bpy.context.object
    obj.name = name

    obj.data.materials.append(material)

    obj.rotation_mode = 'QUATERNION'
    obj.rotation_quaternion = direction.to_track_quat('Z', 'Y')

    move_to_collection(obj, COL_OPTICS)
    return obj

