# ------------------------------------------------
# 12. SMILEY GENERATOR
# ------------------------------------------------
#
# Coordinate system:
#   u = horizontal
#   v = vertical
#
# Generates a clean binary smiley without image files.
# ------------------------------------------------

def smiley_pixel(x, y, nx, ny):
    # Normalize to [-1, +1]
    u = (x + 0.5) / nx * 2.0 - 1.0
    v = (y + 0.5) / ny * 2.0 - 1.0

    # Outer face circle
    r = math.sqrt(u*u + v*v)

    if r > 0.88:
        return 0

    # Eyes
    left_eye  = ((u + 0.30) / 0.11)**2 + ((v - 0.25) / 0.16)**2
    right_eye = ((u - 0.30) / 0.11)**2 + ((v - 0.25) / 0.16)**2

    if left_eye < 1.0 or right_eye < 1.0:
        return 1

    # Smile:
    # lower semicircular band.
    smile_radius = math.sqrt(u*u + (v + 0.05)*(v + 0.05))

    # Main lower arc
    if (
        -0.55 < u < 0.55 and
        -0.58 < v < 0.02 and
        abs(smile_radius - 0.48) < 0.07
    ):
        return 1

    # Smile corners
    if (
        (u < -0.48 or u > 0.48) and
        -0.18 < v < 0.10
    ):
        return 1

    return 0

