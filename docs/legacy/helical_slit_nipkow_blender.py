def make_material(name, base_color, metallic=0.0, roughness=0.5,
                  emission=None, emission_strength=0.0,
                  alpha=1.0):
    mat = bpy.data.materials.get(name)
    if mat is None:
        mat = bpy.data.materials.new(name)

    mat.diffuse_color = (
        base_color[0],
        base_color[1],
        base_color[2],
        alpha
    )

    mat.use_nodes = True
    nodes = mat.node_tree.nodes
    links = mat.node_tree.links

    nodes.clear()

    out = nodes.new("ShaderNodeOutputMaterial")

    if emission is not None and emission_strength > 0:
        shader = nodes.new("ShaderNodeEmission")
        shader.inputs["Color"].default_value = (
            emission[0], emission[1], emission[2], 1.0
        )
        shader.inputs["Strength"].default_value = emission_strength
    else:
        shader = nodes.new("ShaderNodeBsdfPrincipled")
        shader.inputs["Base Color"].default_value = (
            base_color[0], base_color[1], base_color[2], 1.0
        )
        shader.inputs["Metallic"].default_value = metallic
        shader.inputs["Roughness"].default_value = roughness

    links.new(shader.outputs[0], out.inputs["Surface"])

    return mat


