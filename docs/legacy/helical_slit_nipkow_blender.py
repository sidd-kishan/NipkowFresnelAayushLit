# ------------------------------------------------
# 6. CONTINUOUS HELICAL SLIT
# ------------------------------------------------
#
# A real slit would be cut into the drum.
# For a Blender demonstration we represent its two edges with
# a glowing helical curve and make the drum dark.
#
# The helix wraps around the X axis.
#
# x = axial coordinate
# theta = helical angular coordinate
# y = r cos(theta)
# z = r sin(theta)
#
# The lower part of the drum is the projection side.
# ------------------------------------------------

def make_helix(name, radius, turns, length, samples, material,
                phase=0.0, collection=None, bevel=0.00008):

    curve = bpy.data.curves.new(name, type='CURVE')
    curve.dimensions = '3D'
    curve.resolution_u = 1
    curve.bevel_depth = bevel
    curve.bevel_resolution = 2

    spline = curve.splines.new('POLY')
    spline.points.add(samples - 1)

    for i in range(samples):
        u = i / float(samples - 1)
        x = -length / 2.0 + u * length
        theta = phase + turns * 2.0 * math.pi * u

        y = radius * math.cos(theta)
        z = radius * math.sin(theta)

        spline.points[i].co = (x, y, z, 1.0)

    obj = bpy.data.objects.new(name, curve)
    collection.objects.link(obj)
    obj.data.materials.append(material)
    return obj

